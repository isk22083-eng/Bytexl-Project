"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import { useLanguage } from "@/lib/i18n";

type RecordDetail = {
  id: string;
  document_type: string;
  document_date: string | null;
  patient_name_guess: string | null;
  summary_english: string;
  summary_telugu: string | null;
  disclaimer: string;
  patients: {
    full_name: string;
    date_of_birth: string | null;
    gender: string | null;
    abha_id: string | null;
  } | null;
  medications: {
    id: string;
    name: string;
    dosage: string | null;
    frequency: string | null;
    duration: string | null;
    instructions: string | null;
  }[];
  lab_observations: {
    id: string;
    test_name: string;
    value: string;
    unit: string | null;
    reference_range: string | null;
    is_abnormal: boolean;
    plain_language_note: string | null;
  }[];
  diagnoses: { id: string; description: string; diagnosis_date: string | null }[];
};

export default function RecordDetailClient({ id }: { id: string }) {
  const { lang } = useLanguage();
  const [record, setRecord] = useState<RecordDetail | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    fetch(`/api/records/${id}`)
      .then((res) => res.json())
      .then((data) => {
        if (data.error) throw new Error(data.error);
        setRecord(data.record as RecordDetail);
      })
      .catch((err) => setError(err instanceof Error ? err.message : "Failed to load."));
  }, [id]);

  if (error) {
    return (
      <div className="mx-auto max-w-3xl px-4 py-12">
        <p className="rounded-lg bg-red-50 p-3 text-sm text-red-700 dark:bg-red-950 dark:text-red-300">
          {error}
        </p>
      </div>
    );
  }

  if (!record) {
    return (
      <div className="mx-auto max-w-3xl px-4 py-12 text-sm text-black/60 dark:text-white/60">
        {lang === "te" ? "లోడ్ అవుతోంది..." : "Loading..."}
      </div>
    );
  }

  const patient = record.patients;

  return (
    <div className="mx-auto max-w-3xl px-4 py-12 print:py-4">
      <div className="mb-6 flex items-center justify-between print:hidden">
        <Link href="/timeline" className="text-sm hover:underline">
          ← {lang === "te" ? "టైమ్‌లైన్‌కు తిరిగి వెళ్ళండి" : "Back to timeline"}
        </Link>
        <button
          type="button"
          onClick={() => window.print()}
          className="rounded-full bg-black px-5 py-2 text-sm font-medium text-white hover:bg-black/80 dark:bg-white dark:text-black"
        >
          {lang === "te" ? "ప్రింట్ / PDF గా సేవ్ చేయండి" : "Print / Save as PDF"}
        </button>
      </div>

      <header className="border-b border-black/10 pb-4 dark:border-white/10">
        <h1 className="text-xl font-bold">
          {lang === "te" ? "ఆరోగ్య రికార్డు సారాంశం" : "Health Record Summary"}
        </h1>
        <p className="mt-1 text-xs text-black/50 dark:text-white/50">
          {lang === "te" ? "హెల్త్ కోపైలట్ ద్వారా రూపొందించబడింది" : "Generated by Health Copilot"}
        </p>
      </header>

      <section className="mt-6 grid gap-x-8 gap-y-2 text-sm sm:grid-cols-2">
        <div>
          <span className="text-black/50 dark:text-white/50">
            {lang === "te" ? "రోగి పేరు: " : "Patient name: "}
          </span>
          {patient?.full_name ?? record.patient_name_guess ?? "—"}
        </div>
        <div>
          <span className="text-black/50 dark:text-white/50">
            {lang === "te" ? "పుట్టిన తేదీ: " : "Date of birth: "}
          </span>
          {patient?.date_of_birth ?? "—"}
        </div>
        <div>
          <span className="text-black/50 dark:text-white/50">
            {lang === "te" ? "లింగం: " : "Gender: "}
          </span>
          {patient?.gender ?? "—"}
        </div>
        <div>
          <span className="text-black/50 dark:text-white/50">ABHA ID: </span>
          {patient?.abha_id ?? "—"}
        </div>
        <div>
          <span className="text-black/50 dark:text-white/50">
            {lang === "te" ? "సందర్శన తేదీ: " : "Visit / document date: "}
          </span>
          {record.document_date ?? "—"}
        </div>
        <div>
          <span className="text-black/50 dark:text-white/50">
            {lang === "te" ? "పత్రం రకం: " : "Document type: "}
          </span>
          {record.document_type.replace("_", " ")}
        </div>
      </section>

      {record.diagnoses.length > 0 && (
        <section className="mt-6">
          <h2 className="font-semibold">{lang === "te" ? "రోగనిర్ధారణలు" : "Diagnoses"}</h2>
          <ul className="mt-2 list-inside list-disc text-sm">
            {record.diagnoses.map((d) => (
              <li key={d.id}>{d.description}</li>
            ))}
          </ul>
        </section>
      )}

      {record.medications.length > 0 && (
        <section className="mt-6">
          <h2 className="font-semibold">{lang === "te" ? "మందులు" : "Medications"}</h2>
          <table className="mt-2 w-full border-collapse text-sm">
            <thead>
              <tr className="border-b border-black/10 text-left text-xs text-black/50 dark:border-white/10 dark:text-white/50">
                <th className="py-1 pr-2">{lang === "te" ? "పేరు" : "Name"}</th>
                <th className="py-1 pr-2">{lang === "te" ? "మోతాదు" : "Dosage"}</th>
                <th className="py-1 pr-2">{lang === "te" ? "ఫ్రీక్వెన్సీ" : "Frequency"}</th>
                <th className="py-1">{lang === "te" ? "వ్యవధి" : "Duration"}</th>
              </tr>
            </thead>
            <tbody>
              {record.medications.map((m) => (
                <tr key={m.id} className="border-b border-black/5 dark:border-white/5">
                  <td className="py-1.5 pr-2 font-medium">{m.name}</td>
                  <td className="py-1.5 pr-2">{m.dosage ?? "—"}</td>
                  <td className="py-1.5 pr-2">{m.frequency ?? "—"}</td>
                  <td className="py-1.5">{m.duration ?? "—"}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </section>
      )}

      {record.lab_observations.length > 0 && (
        <section className="mt-6">
          <h2 className="font-semibold">{lang === "te" ? "పరీక్ష ఫలితాలు" : "Lab Observations"}</h2>
          <ul className="mt-2 space-y-1 text-sm">
            {record.lab_observations.map((o) => (
              <li key={o.id} className={o.is_abnormal ? "font-semibold text-red-600 dark:text-red-400" : ""}>
                {o.test_name}: {o.value} {o.unit} {o.reference_range && `(ref: ${o.reference_range})`}
              </li>
            ))}
          </ul>
        </section>
      )}

      <section className="mt-6">
        <h2 className="font-semibold">{lang === "te" ? "సారాంశం" : "Summary"}</h2>
        <p className="mt-2 text-sm">{record.summary_english}</p>
        {record.summary_telugu && (
          <>
            <h3 className="mt-3 text-sm font-semibold">తెలుగు సారాంశం</h3>
            <p className="mt-1 text-sm">{record.summary_telugu}</p>
          </>
        )}
      </section>

      <footer className="mt-8 border-t border-black/10 pt-4 text-xs text-black/50 dark:border-white/10 dark:text-white/50">
        {record.disclaimer}
      </footer>
    </div>
  );
}
